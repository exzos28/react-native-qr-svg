import React, { useMemo } from 'react';
import clsx from 'clsx';
import {
  qrCodeToSvgString,
  type QrSvgStringOptions,
} from '../../../../packages/react-native-qr-svg/src/svgString';
import styles from './QrPreview.module.css';

export type QrPreviewProps = QrSvgStringOptions & {
  /** Emoji drawn over the cleared logo area. */
  logo?: string;
  /** Rendered width in CSS pixels. */
  width?: number;
  caption?: React.ReactNode;
  className?: string;
};

/**
 * Renders a QR code in the browser with the library's own geometry code
 * (`qrCodeToSvgString`): what you see is what the component draws.
 */
export default function QrPreview({
  logo,
  width = 220,
  caption,
  className,
  ...options
}: QrPreviewProps) {
  const result = useMemo(() => {
    try {
      return {
        svg: qrCodeToSvgString({
          quietZone: 2,
          ...options,
          logoCells: logo ? (options.logoCells ?? 6) : options.logoCells,
        }),
        error: null,
      };
    } catch (cause) {
      return { svg: null, error: (cause as Error).message };
    }
    // The options object is recreated on every render; its JSON is the key.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [JSON.stringify(options), logo]);

  return (
    <figure className={clsx(styles.figure, className)} style={{ width }}>
      <div className={styles.frame}>
        {result.svg ? (
          <div
            className={styles.svg}
            // The SVG is generated by the library from the options above;
            // attribute values are escaped there.
            dangerouslySetInnerHTML={{ __html: result.svg }}
          />
        ) : (
          <div className={styles.error}>{result.error}</div>
        )}
        {logo && result.svg && <span className={styles.logo}>{logo}</span>}
      </div>
      {caption && <figcaption className={styles.caption}>{caption}</figcaption>}
    </figure>
  );
}

/** A row of previews that wraps on narrow screens. */
export function QrGallery({ children }: { children: React.ReactNode }) {
  return <div className={styles.gallery}>{children}</div>;
}
